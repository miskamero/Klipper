const excluded =
	/(^|\/)(?:\.env(?:\.[^/]*)?|\.git|\.aws|\.ssh|local|localBAK|\.validation|tools|native-deps|release|node_modules|target|dist|gen|generated|autogenerated|coverage|private|secrets?|fixtures?|screenshots?|logs?|tmp|temp|\.cache)(\/|$)/i;
const maintainedType = /\.(?:[cm]?js|jsx|tsx?|scss|css|json|rs|sql|toml|lock|txt|ico|png|svg)$/i;

export function sourceEligible(name) {
	if (!name || isAbsolute(name) || name.includes("\\") || name.includes(":")) return false;
	if (name.split("/").some((part) => !part || part === "." || part === "..")) return false;
	return (
		!excluded.test(name) &&
		(configurations.includes(name) ||
			(directories.some((directory) => name.startsWith(`${directory}/`)) &&
				maintainedType.test(name)))
	);
}

function git(root, args, input) {
	const result = spawnSync(
		"git",
		["-c", `safe.directory=${resolve(root).replaceAll("\\", "/")}`, ...args],
		{
			cwd: root,
			input,
			encoding: "utf8",
			windowsHide: true,
			shell: false,
			timeout: 30_000,
			maxBuffer: 8 * 1024 * 1024,
		},
	);
	if (result.error) throw result.error;
	if (result.status !== 0 && !(args[0] === "check-ignore" && result.status === 1))
		throw new Error(`Source selection requires a Git checkout: ${result.stderr}`);
	return result.stdout.split("\0").filter(Boolean);
}

export async function regularSource(root, name) {
	if (!sourceEligible(name)) throw new Error(`Unsafe source path: ${name}`);
	// Check every ancestor: lstat(file) alone misses directory junctions on Windows.
	let current = resolve(root);
	for (const part of name.split("/")) {
		current = join(current, part);
		if ((await lstat(current)).isSymbolicLink()) throw new Error(`Linked source path: ${name}`);
	}
	const canonicalRoot = await realpath(root);
	const rel = relative(canonicalRoot, await realpath(current));
	if (isAbsolute(rel) || rel === ".." || rel.startsWith("../") || rel.startsWith("..\\"))
		throw new Error(`Escaping source path: ${name}`);
	const info = await lstat(current);
	if (!info.isFile() || info.nlink > 1) throw new Error(`Non-regular/aliased source: ${name}`);
	return info;
}

export async function sourceState(root) {
	// Vite would consume these ignored files even though they cannot enter the source bundle.
	const localEnvironment = [".env", ".env.local", ".env.production", ".env.production.local"];
	if ((await readdir(root)).some((name) => localEnvironment.includes(name)))
		throw new Error(
			"Packaging cannot use private local .env build inputs; use a checkout without them",
		);
	// Include intentional dirty/untracked maintained inputs, never ignored local data.
	const candidates = git(root, [
		"ls-files",
		"-z",
		"--cached",
		"--others",
		"--exclude-standard",
		"--",
		...configurations,
		...directories,
	]).filter(sourceEligible);
	const ignored = new Set(
		candidates.length
			? git(
					root,
					["check-ignore", "--no-index", "-z", "--stdin"],
					candidates.join("\0") + "\0",
				)
			: [],
	);
	const result = {};
	for (const name of [...new Set(candidates)].filter((name) => !ignored.has(name)).sort()) {
		try {
			const info = await regularSource(root, name);
			result[name] = {
				sha256: await checksum(join(root, name)),
				size: info.size,
				mtime: info.mtimeMs,
				ctime: info.ctimeMs,
				inode: info.ino,
			};
		} catch (error) {
			if (error.code !== "ENOENT") throw error; // Deleted tracked files are absent in a dirty build.
		}
	}
	return result;
}

export async function assertSourceUnchanged(root, expected) {
	if (JSON.stringify(await sourceState(root)) !== JSON.stringify(expected))
		throw new Error(
			"Maintained source changed during packaging; discard this build and rerun with a stable checkout",
		);
}
